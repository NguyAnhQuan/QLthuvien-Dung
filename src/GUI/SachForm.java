    private void loadTableData() {
        List<Sach> danhSachSach = sachLG.getAllSachs();
        tableModel = (DefaultTableModel) jTable1.getModel();
        tableModel.setRowCount(0);
        for (Sach s : danhSachSach) {
            tableModel.addRow(
                    new Object[] { s.getId(), s.getTenSach(), s.getTacGia(), s.getNamXuatBan(), s.getTheLoai() });
        }
    }

    private void jTable1MouseClicked(MouseEvent evt) {
        int row = jTable1.getSelectedRow();
        if (row >= 0) {
            try {
                Object IdObj = jTable1.getValueAt(row, 0);
                Object tenSachObj = jTable1.getValueAt(row, 1);
                Object tacGiaObj = jTable1.getValueAt(row, 2);
                Object namXuatBanObj = jTable1.getValueAt(row, 3);
                Object theLoaiObj = jTable1.getValueAt(row, 4);

                String Id = IdObj instanceof String ? (String) IdObj : IdObj.toString();
                String tenSach = tenSachObj instanceof String ? (String) tenSachObj : tenSachObj.toString();
                String tacGia = tacGiaObj instanceof String ? (String) tacGiaObj : tacGiaObj.toString();

                int namXuatBan = namXuatBanObj instanceof Number ? ((Number) namXuatBanObj).intValue()
                        : Integer.parseInt(namXuatBanObj.toString());
                String theLoai = theLoaiObj instanceof String ? (String) theLoaiObj : theLoaiObj.toString();

                jTextField1.setText(Id);
                jTextField2.setText(tenSach);
                jTextField3.setText(tacGia);
                jTextField4.setText(String.valueOf(namXuatBan));
                jTextField5.setText(theLoai);
            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, "Lỗi khi xử lý dữ liệu: " + e.getMessage(), "Lỗi",
                        JOptionPane.ERROR_MESSAGE);
            }
        } else {
            JOptionPane.showMessageDialog(null, "Vui lòng chọn một hàng trong bảng.", "Cảnh báo",
                    JOptionPane.WARNING_MESSAGE);
        }
    }

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_jButton1ActionPerformed
        String Id = jTextField1.getText().trim();
        String tenSach = jTextField2.getText().trim();
        String tacGia = jTextField3.getText().trim();
        String namXuatBantxt = jTextField4.getText().trim();
        String theLoai = jTextField5.getText().trim();
        int namXuatBan = 0;
        try {
            namXuatBan = Integer.parseInt(namXuatBantxt);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Phải là một số hợp lệ!");
        }

        Sach s = new Sach(Id, tenSach, tacGia, namXuatBan, theLoai);
        boolean success = sachLG.themSach(s);
        if (success) {
            JOptionPane.showMessageDialog(this, "Thêm thành công!");
            loadTableData();
        } else {
            JOptionPane.showMessageDialog(this, "Thêm thất bại!");
        }
    }// GEN-LAST:event_jButton1ActionPerformed

