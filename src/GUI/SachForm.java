    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_jButton4ActionPerformed
        String id = jTextField1.getText().trim();
        List<Sach> danhSachSach = sachLG.timKiemSach(id);

        tableModel.setRowCount(0); // Xóa dữ liệu hiện tại trên bảng

        if (danhSachSach != null && !danhSachSach.isEmpty()) {
            for (Sach s : danhSachSach) {
                tableModel.addRow(
                        new Object[] { s.getId(), s.getTenSach(), s.getTacGia(), s.getNamXuatBan(), s.getTheLoai() });
            }
        } else {
            JOptionPane.showMessageDialog(this, "Không tìm thấy!");
        }
    }// GEN-LAST:event_jButton4ActionPerformed

